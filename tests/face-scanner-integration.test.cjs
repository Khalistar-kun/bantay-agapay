const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const base = path.resolve(__dirname, '..', 'public', 'client-demo')
test('client face scan loads shared on-device scanner before visitor application',()=>{
 const html=fs.readFileSync(path.join(base,'index.html'),'utf8')
 assert.match(html,/\/client-demo\/face-scanner\.js/)
 assert.ok(html.indexOf('face-scanner.js') < html.indexOf('script.js'))
})
test('manual camera capture cannot be mislabelled a completed motion scan',()=>{
 const code=fs.readFileSync(path.join(base,'script.js'),'utf8')
 assert.doesNotThrow(()=>new vm.Script(code))
 assert.match(code,/if\(!manual&&\(!state\.faceScanReady\|\|!faceScanSession\?\.isReady\(\)\)\)/)
 assert.match(code,/state\.faceReviewOnly=!!manual/)
 assert.match(code,/state\.faceReviewOnly=true;stopCamera\(\)/)
 assert.match(code,/faceScanSession\.stop\(\)/)
 assert.match(code,/cameraSerial\+\+/)
 assert.match(code,/window\.BantayFaceScan\.start/)
 assert.match(code,/Face photo scanning/)
 assert.match(code,/Security will still verify your identity/)
})
test('original React face scanning delegates to shared scanner; skin pixel simulation removed',()=>{
 const code=fs.readFileSync(path.join(__dirname,'../components/visitor/FaceDetection.tsx'),'utf8')
 assert.match(code,/\/client-demo\/face-scanner\.js/)
 assert.match(code,/scanner\.start\(video/)
 assert.match(code,/Motion check complete/)
 assert.doesNotMatch(code,/faceScore|faceConfidence|skin tones|FACE_VERIFIED/)
})
