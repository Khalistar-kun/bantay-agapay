const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = path.resolve(__dirname, '..', 'public', 'client-demo')
test('logo opening animation is loaded from same origin with a skip control',()=>{
  const html = fs.readFileSync(path.join(base,'index.html'),'utf8')
  assert.match(html,/id="ba-intro"/)
  assert.match(html,/id="ba-intro-skip"/)
  assert.match(html,/\/client-demo\/bantay-agapay-logo\.png/)
  assert.match(html,/\/client-demo\/intro\.css/)
  assert.match(html,/\/client-demo\/intro\.js/)
})
test('intro respects reduced motion, never blocks the page indefinitely',()=>{
  const css = fs.readFileSync(path.join(base,'intro.css'),'utf8')
  const js = fs.readFileSync(path.join(base,'intro.js'),'utf8')
  assert.match(css,/prefers-reduced-motion:\s*reduce/)
  assert.match(js,/setTimeout\(dismiss,\s*2250\)/)
  assert.match(js,/sessionStorage\.setItem\('ba_intro_seen'/)
  assert.match(js,/Escape/)
  assert.match(js,/intro\.remove\(\)/)
  assert.doesNotThrow(() => new (require('node:vm').Script)(js))
})
