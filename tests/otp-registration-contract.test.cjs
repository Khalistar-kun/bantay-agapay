const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const get=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8')
const otp=get('app/api/returning/otp/route.ts')
const registration=get('app/api/pre-register/route.ts')
const ui=get('app/pre-register/page.tsx')
const sql=get('supabase/migrations/13_required_visitor_phone_otp.sql')

test('SMS is required for new visitors and request does not require prior visitor record',()=>{
 const block=otp.slice(otp.indexOf("if(action==='request')"),otp.indexOf("const code=body.code"))
 assert.match(block,/sendReturningOtp\(phone,code\)/)
 assert.doesNotMatch(block,/\.from\('visitors'\)/)
 assert.match(otp,/manualRegistrationAvailable:false/)
})
test('verification returns random proof and backend validates it before any visitor photo upload',()=>{
 assert.match(otp,/randomBytes\(32\)\.toString\('hex'\)/)
 assert.match(otp,/visitor_phone_verifications/)
 assert.match(registration,/consume_phone_verification/)
 assert.match(registration,/proofValid!==true/)
 assert.ok(registration.indexOf("rpc('consume_phone_verification'") < registration.indexOf("storage.from('visitor-faces').upload"))
 assert.match(ui,/verificationToken/)
 assert.match(ui,/Verify your mobile number by SMS before proceeding/)
})
test('proof is tied to phone and consumed atomically, with no anonymous access',()=>{
 assert.match(sql,/WHERE proof_hash = p_proof_hash/)
 assert.match(sql,/AND phone_hash = p_phone_hash/)
 assert.match(sql,/AND consumed_at IS NULL/)
 assert.match(sql,/AND expires_at > now\(\)/)
 assert.match(sql,/REVOKE EXECUTE ON FUNCTION public.consume_phone_verification/)
})
test('no paid gateway fallback or unverified manual online self-registration',()=>{
 assert.match(registration,/smsGatewayConfigured\(\)/)
 assert.match(ui,/Online registration is paused/)
 assert.doesNotMatch(otp+registration,/BA_SMS_GATEWAY_URL/)
})
